  def test_blocked_address_matches_the_gem
    mismatches = CASES.reject { |addr, blocked| Surfguard.blocked_address?(addr) == blocked }
    assert_empty mismatches.map(&:first),
      "blocked_address? disagrees with surfguard 910be917 on these addresses"
  end

  # An IP-LITERAL host skips DNS entirely, which is the one path through
  # `resolve_public_ips` a unit test can drive without a resolver.
  def test_resolve_public_ips_passes_a_public_literal_through
    assert_equal [ "8.8.8.8" ], Surfguard.resolve_public_ips("8.8.8.8")
  end

  # A literal that resolves to itself and is refused: the host RESOLVED,
  # so this is an empty list, not Unresolvable. The distinction is the
  # whole reason the gem carries two error classes — see the header of
  # `surfguard.rb`.
  def test_resolve_public_ips_is_empty_for_a_blocked_literal
    assert_equal [], Surfguard.resolve_public_ips("169.254.169.254")
  end

  # The ordering rule `resolve_public_ips` implements — IPv4 ahead of
  # IPv6 — over the two families' predicates. A NAME would exercise it
  # end to end, but nothing here has a resolver to answer one
  # (`runtime/ruby/resolv.rb` raises by design), and campfire's own
  # `Push::SubscriptionTest` already drives that half with
  # `Resolv.getaddresses` stubbed.
  def test_both_families_pass_the_policy_and_are_distinguishable
    v4 = IPAddr.new("8.8.8.8")
    v6 = IPAddr.new("2606:4700:4700::1111")
    refute Surfguard.blocked_ipaddr?(v4)
    refute Surfguard.blocked_ipaddr?(v6)
    assert v4.ipv4?
    refute v6.ipv4?
  end
end
