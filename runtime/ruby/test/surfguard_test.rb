# The Surfguard port's RULE TABLE, address by address.
#
# A FRAMEWORK test (`tests/runtime_ruby_unit.rs` runs every file under
# `runtime/ruby/test/` on each `cargo test`), not one that ships into an
# emitted tree.
#
# WHY THIS FILE EXISTS. `runtime/ruby/surfguard.rb` is a PORT of
# basecamp/surfguard, and unlike `ipaddr.rb` it has no stdlib twin on
# ANY target to fall back on — the gem is a git dependency, so no lane
# runs the original. A port with no twin is exactly the thing that fails
# quietly: an address wrongly called public is an SSRF fetch that
# should not have happened, and nothing raises.
#
# The expectations below are the GEM's answers, generated by running
# surfguard at the revision campfire's Gemfile.lock pins
# (910be917fd0ab782c5ea939698d44f26694a501d) over this list:
#
#     ruby -Ilib -rsurfguard -e 'ADDRS.each { |a|
#       puts [a, Surfguard.blocked_address?(a)].inspect }'
#
# Regenerate the same way if the table ever needs extending; do not
# hand-write an expectation. (The one time that rule was broken on the
# IPAddr port, the hand-written row was the only red.)
#
# The list covers, in order: public v4; every DISALLOWED_IPV4 range and
# the addresses either side of each boundary; v6 loopback / ULA /
# link-local / site-local / multicast and every DISALLOWED_IPV6 range;
# a public v6; IPv4-mapped and IPv4-compatible (refused whatever they
# wrap); NAT64 well-known (decoded) and RFC 8215 local-use (refused
# whole); SIIT `::ffff:0:0:0/96` (decoded); and a malformed string,
# which errs closed.
