//! Entry point — emits `app/__main__.py`.

use std::path::PathBuf;

use super::super::EmittedFile;
use crate::App;

/// Emit `app/__main__.py` — the `python -m app` entry point that the
/// compare driver invokes. Opens the DB and starts the server; every
/// request flows through the overlay's `app/v2/dispatch.handle`
/// (which layout-wraps itself), and broadcast partials render inline
/// at the model's `after_*_commit` call sites — so neither the
/// legacy layout callable nor cable partial registration exists
/// anymore.
pub(super) fn emit_py_main(_app: &App) -> EmittedFile {
    let content = "\
# Generated by Roundhouse.
from __future__ import annotations

from app import server
from app.schema_sql import CREATE_TABLES

def main() -> None:
    server.start(schema_sql=CREATE_TABLES)

if __name__ == \"__main__\":
    main()
";
    EmittedFile {
        path: PathBuf::from("app/__main__.py"),
        content: content.to_string(),
    }
}
